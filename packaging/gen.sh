#!/usr/bin/env bash
# gen.sh — regenerate all distribution manifests for a release.
# Reads version + SHA256SUMS.txt so every manifest stays in lockstep
# with the published binaries. Run after building release assets:
#   ./packaging/gen.sh 0.0.6 release/*/SHA256SUMS.txt
set -euo pipefail
cd "$(dirname "$0")"

VER="${1:?usage: gen.sh <version> <SHA256SUMS.txt>}"
SUMS="${2:?usage: gen.sh <version> <SHA256SUMS.txt>}"
REPO="shizukutanaka/fabi"
BASE="https://github.com/$REPO/releases/download/v$VER"

sha() { grep "fabi-$1\$" "$SUMS" | awk '{print $1}'; }

WIN=$(sha windows-amd64.exe)
LIN=$(sha linux-amd64)
DAMD=$(sha darwin-amd64)
DARM=$(sha darwin-arm64)

# --- scoop ---
cat > scoop/fabi.json <<EOF
{
    "version": "$VER",
    "description": "Universal AI Control Plane — scan your AI estate, keep one honest ledger, subtract what you don't need.",
    "homepage": "https://github.com/$REPO",
    "license": "MIT",
    "architecture": {
        "64bit": {
            "url": "$BASE/fabi-windows-amd64.exe#/fabi.exe",
            "hash": "$WIN"
        }
    },
    "bin": "fabi.exe",
    "checkver": { "github": "https://github.com/$REPO" },
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "$BASE/fabi-windows-amd64.exe#/fabi.exe"
            }
        }
    }
}
EOF

# --- homebrew ---
cat > homebrew/fabi.rb <<EOF
# frozen_string_literal: true

# GENERATED by packaging/gen.sh — do not hand-edit; regenerate per release.
class Fabi < Formula
  desc "Universal AI Control Plane — the honest eye on your AI estate"
  homepage "https://github.com/$REPO"
  version "$VER"
  license "MIT"

  on_macos do
    if Hardware::CPU.intel?
      url "$BASE/fabi-darwin-amd64"
      sha256 "$DAMD"
    else
      url "$BASE/fabi-darwin-arm64"
      sha256 "$DARM"
    end
  end

  on_linux do
    if Hardware::CPU.intel?
      url "$BASE/fabi-linux-amd64"
      sha256 "$LIN"
    end
  end

  def install
    bin.install Dir["fabi-*"].first => "fabi"
  end

  test do
    assert_match "fabi", shell_output("#{bin}/fabi version")
  end
end
EOF

# --- winget (3 files) ---
cat > winget/Fabi.Fabi.yaml <<EOF
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.version.1.9.0.schema.json
PackageIdentifier: Fabi.Fabi
PackageVersion: $VER
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.9.0
EOF

cat > winget/Fabi.Fabi.installer.yaml <<EOF
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.installer.1.9.0.schema.json
PackageIdentifier: Fabi.Fabi
PackageVersion: $VER
InstallerType: portable
InstallerLocale: en-US
UpgradeBehavior: install
Commands:
  - fabi
Installers:
  - Architecture: x64
    InstallerUrl: $BASE/fabi-windows-amd64.exe
    InstallerSha256: $WIN
ManifestType: installer
ManifestVersion: 1.9.0
EOF

cat > winget/Fabi.Fabi.locale.en-US.yaml <<EOF
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.defaultLocale.1.9.0.schema.json
PackageIdentifier: Fabi.Fabi
PackageVersion: $VER
PackageLocale: en-US
Publisher: Fabi
PackageName: Fabi
PackageUrl: https://github.com/$REPO
License: MIT
LicenseUrl: https://github.com/$REPO/blob/master/LICENSE
ShortDescription: Universal AI Control Plane — scan your AI estate, keep one honest ledger, subtract what you don't need.
Tags:
  - ai
  - llm
  - local-ai
  - inventory
  - ollama
  - cli
ManifestType: defaultLocale
ManifestVersion: 1.9.0
EOF

echo "manifests regenerated for v$VER"
grep -rl "$VER" scoop/ homebrew/ winget/ | sort
